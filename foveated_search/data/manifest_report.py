"""Summary stats (markdown) and a contact sheet for the eval manifest."""

from __future__ import annotations

import random
import statistics
from collections import Counter
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

from foveated_search.config import REPO_ROOT, Config
from foveated_search.data.fetch_images import eval_image_path


def _pct(a: int, b: int) -> str:
    return f"{a} ({100 * a / b:.1f}%)" if b else "0"


def write_stats(cfg: Config, rows: list[dict], dev: list[dict]) -> str:
    n = len(rows)
    pos = [r for r in rows if not r["is_negative"]]
    neg = [r for r in rows if r["is_negative"]]
    food = cfg.get_key("eval.food_supercategory")
    L: list[str] = ["# Step 3: eval manifest stats", "",
                    f"Generated by `make eval-manifest` (seed {cfg['seed']}, configs/eval.yaml).", ""]
    L += ["## Overview", "", "| | count |", "|---|---|",
          f"| queries (= distinct images) | {n} ({len({r['image_id'] for r in rows})} images) |",
          f"| positives | {_pct(len(pos), n)} |", f"| negatives | {_pct(len(neg), n)} |",
          f"| `{food}` queries, positive | {_pct(sum(r['query'] == food for r in pos), len(pos))} of positives |",
          f"| `{food}` queries, negative | {_pct(sum(r['query'] == food for r in neg), len(neg))} of negatives |",
          f"| single-category queries | {sum(r['query_type'] == 'category' for r in rows)} |",
          f"| distinct query categories (single) | {len({r['query'] for r in rows if r['query_type'] == 'category'})} |",
          f"| dev subset | {len(dev)} queries: {sum(not r['is_negative'] for r in dev)} pos / "
          f"{sum(r['is_negative'] for r in dev)} neg, {sum(r['query'] == food for r in dev)} `{food}` |", ""]

    sb = Counter(r["size_bucket"] for r in pos)
    L += ["## Target size (positives)", "",
          "Size bucket = COCO definition on the largest target instance's segmentation area "
          f"(small < 32², medium < 96², large ≥ 96²). Minimum largest-box area: "
          f"{cfg.get_key('eval.min_box_area_frac') * 100:.1f}% of the image.", "",
          "| bucket | positives |", "|---|---|"]
    L += [f"| {b} | {_pct(sb[b], len(pos))} |" for b in ["small", "medium", "large"]]
    fr = [r["max_box_area_frac"] for r in pos]
    q = statistics.quantiles(fr, n=10)
    L += ["", f"Largest target box as a fraction of the image: min {min(fr):.4f}, p10 {q[0]:.4f}, "
          f"median {statistics.median(fr):.4f}, p90 {q[-1]:.4f}, max {max(fr):.4f}.", ""]

    ni = [r["num_instances"] for r in pos]
    ic = Counter(min(k, 6) for k in ni)
    L += ["## Instances per positive query", "", f"mean {statistics.mean(ni):.2f}, median {statistics.median(ni)}, max {max(ni)}.", "",
          "| instances | queries |", "|---|---|"]
    L += [f"| {k if k < 6 else '6+'} | {ic[k]} |" for k in sorted(ic)]
    fpos = [r for r in pos if r["query"] == food]
    fc = Counter(c for r in fpos for c in set(r["gt_category_names"]))
    L += ["", f"Food classes present in `{food}` positives (images containing each): "
          + ", ".join(f"{k} {v}" for k, v in sorted(fc.items(), key=lambda kv: (-kv[1], kv[0]))), ""]  # ties by name: deterministic

    ws, hs = [r["width"] for r in rows], [r["height"] for r in rows]
    L += ["## Image sizes", "", f"width {min(ws)}-{max(ws)} px, height {min(hs)}-{max(hs)} px; "
          f"{sum(w > h for w, h in zip(ws, hs))} landscape, {sum(w < h for w, h in zip(ws, hs))} portrait, "
          f"{sum(w == h for w, h in zip(ws, hs))} square.", ""]

    cp = Counter(r["query"] for r in pos if r["query_type"] == "category")
    cn = Counter(r["query"] for r in neg if r["query_type"] == "category")
    cats = sorted(set(cp) | set(cn), key=lambda c: (-(cp[c] + cn[c]), c))
    L += ["## Category distribution (single-category queries)", "",
          f"Positives per category: min {min(cp.values())}, max {max(cp.values())} "
          f"(cap {cfg.get_key('eval.max_per_category')}); {len(cp)} categories with positives, {len(cn)} with negatives.", "",
          "| category | positives | negatives |", "|---|---|---|"]
    L += [f"| {c} | {cp[c]} | {cn[c]} |" for c in cats]
    text = "\n".join(L) + "\n"
    out = REPO_ROOT / cfg.get_key("outputs.stats")
    out.write_text(text)
    print(text)
    print(f"[stats] wrote {out.relative_to(REPO_ROOT)}")
    return text


def contact_sheet(cfg: Config, rows: list[dict], cell_w: int = 320, cols: int = 4) -> Path:
    """~16 sampled queries: mostly positives, plus a few food queries and a few negatives."""
    food = cfg.get_key("eval.food_supercategory")
    k = int(cfg.get_key("outputs.contact_sheet_n"))
    rng = random.Random(int(cfg["seed"]))
    neg = [r for r in rows if r["is_negative"]]
    fpos = [r for r in rows if not r["is_negative"] and r["query"] == food]
    cpos = [r for r in rows if not r["is_negative"] and r["query"] != food]
    pick = rng.sample(neg, 3) + rng.sample(fpos, 4) + rng.sample(cpos, k - 7)
    rng.shuffle(pick)

    cell_h = int(cell_w * 0.75) + 22
    sheet = Image.new("RGB", (cols * cell_w, -(-len(pick) // cols) * cell_h), "black")
    font = ImageFont.load_default()
    for i, r in enumerate(pick):
        im = Image.open(eval_image_path(cfg, r["file_name"])).convert("RGB")
        s = min(cell_w / im.width, (cell_h - 22) / im.height)
        im = im.resize((round(im.width * s), round(im.height * s)), Image.Resampling.LANCZOS)
        d = ImageDraw.Draw(im)
        for (x, y, w, h), name in zip(r["gt_boxes"], r["gt_category_names"]):
            d.rectangle((x * s, y * s, (x + w) * s, (y + h) * s), outline="#00ff66", width=2)
            if r["query"] == food:
                d.text((x * s + 2, y * s + 1), name, fill="#00ff66", font=font)
        x0, y0 = (i % cols) * cell_w, (i // cols) * cell_h
        sheet.paste(im, (x0 + (cell_w - im.width) // 2, y0 + 22))
        tag = "NEG" if r["is_negative"] else f"{r['num_instances']} inst, {r['size_bucket']}"
        ImageDraw.Draw(sheet).text((x0 + 4, y0 + 5), f"{r['query_id']} '{r['query']}' [{tag}]",
                                   fill="#ff5050" if r["is_negative"] else "white", font=font)
    out = REPO_ROOT / cfg.get_key("outputs.contact_sheet")
    sheet.quantize(256).save(out, optimize=True)
    print(f"[sheet] wrote {out.relative_to(REPO_ROOT)} ({out.stat().st_size / 1e3:.0f} KB)")
    return Path(out)
