"""Step 6 reports: dataset stats (markdown) and a grid of samples with targets drawn."""

from __future__ import annotations

import json
import random
import textwrap
from collections import Counter

import numpy as np
from PIL import Image, ImageDraw

from foveated_search.config import REPO_ROOT, Config
from foveated_search.search.viz import _font, save_png


def _pct(a: int, b: int) -> str:
    return f"{a} ({100 * a / b:.1f}%)" if b else "0"


def _table(counter: Counter, total: int, header: str, order=None) -> list[str]:
    keys = order or sorted(counter, key=lambda k: (-counter[k], str(k)))
    return [f"| {header} | samples |", "|---|---|"] + [f"| {k} | {_pct(counter[k], total)} |" for k in keys]


def write_stats(cfg: Config, train: list[dict], val: list[dict], meta: dict) -> None:
    allS = train + val
    n = len(allS)
    L = ["# Step 6: training dataset stats", "",
         f"Generated by `make gen-data` (seed {cfg['seed']}, prompts v{cfg['prompts']['version']}, "
         "configs/train_data.yaml). Data lives on the local disk only.", ""]
    tr_img = {s["meta"]["image_id"] for s in train}
    va_img = {s["meta"]["image_id"] for s in val}
    L += ["## Overview", "", "| | value |", "|---|---|",
          f"| samples | {n} (train {len(train)}, val {len(val)}) |",
          f"| images | {len(tr_img | va_img)} (train {len(tr_img)}, val {len(va_img)}, shared {len(tr_img & va_img)}) |",
          f"| dropped jobs (no valid geometry) | {meta.get('dropped', {})} |"]
    if "fetch_first" in meta:
        f = meta["fetch_first"]
        L.append(f"| image fetch (first run, 32 workers) | {f['n']} images, {f['mb']} MB, {f['seconds']} s ({f['status']}) |")
    if "generation_s" in meta:
        L.append(f"| generation time | {meta['generation_s']} s |")
    for k, v in meta.get("sha256", {}).items():
        L.append(f"| sha256 {k} | `{v}` |")
    L.append("")

    by_type = Counter(s["type"] for s in allS)
    L += ["## By type", ""] + _table(by_type, n, "type", ["where", "look_again", "confirm"]) + [""]
    pol = Counter((s["type"], s["meta"]["polarity"]) for s in allS)
    L += ["## Polarity", "", "| type | polarity | samples |", "|---|---|---|"]
    L += [f"| {t} | {p} | {_pct(c, by_type[t])} |" for (t, p), c in sorted(pol.items())] + [""]
    var = Counter((s["type"], s["meta"]["variant"]) for s in allS if s["type"] != "confirm")
    L += ["## Type 1 / 1b variants (planned)", "", "| type | variant | samples |", "|---|---|---|"]
    L += [f"| {t} | {v} | {_pct(c, by_type[t])} |" for (t, v), c in sorted(var.items())] + [""]
    nok = Counter(s["meta"]["no_kind"] for s in allS if s["type"] == "confirm" and s["meta"]["polarity"] == "no")
    L += ["## Confirm \"no\" crops by kind", ""] + _table(nok, sum(nok.values()), "kind") + [""]
    lab = sum(s["meta"].get("label_on", False) for s in allS if s["type"] == "confirm")
    L += [f"Confirm prompts with the evidence label on: {_pct(lab, by_type['confirm'])}.", ""]

    th = Counter(s["meta"]["thumb_long_side"] for s in allS if s["type"] != "confirm")
    sizes = Counter(f"{s['meta']['sent_w']}x{s['meta']['sent_h']}" for s in allS if s["type"] != "confirm")
    L += ["## Thumbnail long side (Type 1 / 1b)", ""] + _table(th, sum(th.values()), "long side px", sorted(th)) + [""]
    L += ["Most common exact thumbnail sizes sent: " + ", ".join(f"{k} ({v})" for k, v in sizes.most_common(8)), ""]
    cs = Counter(s["meta"]["crop_size"] for s in allS if s["type"] == "confirm")
    L += ["## Crop size (Type 2)", ""] + _table(cs, sum(cs.values()), "crop px", sorted(cs)) + [""]
    sb = Counter(s["meta"]["size_bucket"] for s in allS if s["meta"]["size_bucket"])
    sm = sum(s["meta"]["small"] for s in allS if s["meta"]["size_bucket"])
    L += ["## Target size (positives / yes)", "", "COCO buckets on the pointed-at instance's segmentation area:", ""]
    L += _table(sb, sum(sb.values()), "bucket", ["small", "medium", "large"])
    L += ["", f"Largest instance below the eval's 0.5% minimum area ('small' targets): {_pct(sm, sum(sb.values()))}.", ""]
    food = Counter((s["type"], s["meta"]["query_type"] == "supercategory") for s in allS)
    L += ["## \"food\" share", "", "| type | food samples |", "|---|---|"]
    L += [f"| {t} | {_pct(food[(t, True)], by_type[t])} |" for t in ["where", "look_again", "confirm"]] + [""]
    nchk = Counter(len(s["meta"]["checked_model"]) for s in allS if s["type"] == "look_again")
    L += ["Look-again samples by number of checked points: " + ", ".join(f"{k}: {v}" for k, v in sorted(nchk.items())), ""]
    cats = Counter(s["meta"]["query"] for s in allS)
    vals = [v for k, v in cats.items() if k != "food"]
    L += ["## Query distribution", "",
          f"81 queries (80 categories + food). Single categories: min {min(vals)}, median {int(np.median(vals))}, "
          f"max {max(vals)} samples; food {cats['food']}.", "", "| query | samples |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in sorted(cats.items(), key=lambda kv: (-kv[1], kv[0]))]
    tok = REPO_ROOT / "results/step6_token_stats.json"
    if tok.exists():
        t = json.loads(tok.read_text())
        L += ["", "## Tokens per sample (from the Qwen3-VL processor in .venv-train, `results/step6_token_stats.json`)", "",
              "| type | mean | p95 | mean vision tokens | mean trained (assistant) tokens |", "|---|---|---|---|---|"]
        L += [f"| {k} | {v['mean']:.1f} | {v['p95']:.0f} | {v['vision_mean']:.1f} | {v['assistant_mean']:.1f} |"
              for k, v in t["per_type"].items()]
    out = REPO_ROOT / "results/step6_dataset_stats.md"
    out.write_text("\n".join(L) + "\n")
    print(f"[stats] wrote {out.relative_to(REPO_ROOT)}")


def samples_grid(cfg: Config, samples: list[dict], cell: int = 300, cols: int = 6) -> None:
    from foveated_search.data.train_data import out_dir

    k = int(cfg.get_key("train_data.grid_n"))
    rng = random.Random(f"{cfg['seed']}:grid")
    # every type, polarity and "no" kind is shown; one "food" sample per group where possible
    groups = [
        (lambda s: s["type"] == "where" and s["meta"]["polarity"] == "pos", 5),
        (lambda s: s["type"] == "where" and s["meta"]["polarity"] == "neg", 2),
        (lambda s: s["type"] == "look_again" and s["meta"]["polarity"] == "pos", 4),
        (lambda s: s["type"] == "look_again" and s["meta"]["polarity"] == "neg", 1),
        (lambda s: s["type"] == "confirm" and s["meta"]["polarity"] == "yes" and not s["meta"]["label_on"], 4),
        (lambda s: s["type"] == "confirm" and s["meta"]["polarity"] == "yes" and s["meta"]["label_on"], 1),
        (lambda s: s["type"] == "confirm" and s["meta"].get("no_kind") == "distractor", 3),
        (lambda s: s["type"] == "confirm" and s["meta"].get("no_kind") == "near_miss", 3),
        (lambda s: s["type"] == "confirm" and s["meta"].get("no_kind") == "background", 1),
    ]
    pick = []
    for cond, m in groups:
        cand = [s for s in samples if cond(s)]
        food = [s for s in cand if s["meta"]["query"] == "food"]
        sel = rng.sample(food, min(1, len(food))) + [s for s in rng.sample(cand, m + 1) if s not in food]
        pick += sel[:m]
    pick = pick[:k]
    f_s, f_m = _font(12), _font(14)
    text_h = 126
    W = cols * cell
    H = -(-len(pick) // cols) * (cell + text_h)
    sheet = Image.new("RGB", (W, H), (18, 18, 22))
    d = ImageDraw.Draw(sheet)
    od = out_dir(cfg)
    for i, s in enumerate(pick):
        m = s["meta"]
        im = Image.open(od / s["image"]).convert("RGB")
        scale = min((cell - 8) / im.width, (cell - 8) / im.height)
        rs = Image.Resampling.NEAREST if s["type"] != "confirm" else Image.Resampling.LANCZOS  # thumbnails: true pixels
        big = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), rs)
        bd = ImageDraw.Draw(big)
        for x, y, w, h in m["gt_boxes_sent"]:
            bd.rectangle((x * scale, y * scale, (x + w) * scale, (y + h) * scale), outline=(40, 220, 90), width=2)
        for cx, cy in m.get("checked_model") or []:
            px, py = cx / 1000 * big.width, cy / 1000 * big.height
            bd.line((px - 8, py - 8, px + 8, py + 8), fill=(255, 70, 70), width=3)
            bd.line((px - 8, py + 8, px + 8, py - 8), fill=(255, 70, 70), width=3)
        if m["target_model"]:
            px, py = m["target_model"][0] / 1000 * big.width, m["target_model"][1] / 1000 * big.height
            bd.ellipse((px - 8, py - 8, px + 8, py + 8), outline=(0, 0, 0), width=5)
            bd.ellipse((px - 8, py - 8, px + 8, py + 8), outline=(255, 60, 200), width=3)
        x0, y0 = (i % cols) * cell, (i // cols) * (cell + text_h)
        sheet.paste(big, (x0 + (cell - big.width) // 2, y0 + (cell - big.height) // 2))
        target = s["messages"][1]["content"][0]["text"]
        prompt = s["messages"][0]["content"][1]["text"]
        head = f"{s['type']} | {m['polarity']}" + (f" | {m['no_kind']}" if m.get("no_kind") else "") + \
               f" | {m['sent_w']}x{m['sent_h']} | q: {m['query']}"
        d.text((x0 + 6, y0 + cell + 4), head, fill=(255, 210, 90), font=f_s)
        tl = textwrap.wrap(f"target: {target}", 46)[:2]
        for j, line in enumerate(tl):
            d.text((x0 + 6, y0 + cell + 20 + 14 * j), line, fill=(255, 120, 220), font=f_s)
        for j, line in enumerate(textwrap.wrap(prompt, 46)[:5]):
            d.text((x0 + 6, y0 + cell + 22 + 14 * len(tl) + 14 * j), line, fill=(220, 220, 220), font=f_s)
    leg = "green = target boxes   magenta circle = target point   red X = already-checked points (Type 1b)"
    out = Image.new("RGB", (W, H + 26), (18, 18, 22))
    out.paste(sheet, (0, 26))
    ImageDraw.Draw(out).text((8, 5), leg, fill=(240, 240, 240), font=f_m)
    save_png(out, REPO_ROOT / "results/step6_samples_grid.png")
    print("[grid] wrote results/step6_samples_grid.png")
