"""Generate results/table.md from results/runs/ (never hand-edit the table).

  python -m foveated_search.eval.table          (make table)

Accuracy metrics come from accuracy-mode runs (concurrency 8, split "all"; "test" = the same traces
with dev queries removed). Latency comes ONLY from the latency-mode runs (100-query test subset,
concurrency 1, after warmup).
"""

from __future__ import annotations

import datetime as dt
import json
from pathlib import Path

from foveated_search.config import REPO_ROOT
from foveated_search.eval.metrics import (breakdown, by_query_type, by_size, latency, paired_compare, second_fixation,
                                          summarize)
from foveated_search.eval.runner import eval_config, run_specs
from foveated_search.eval.splits import split_ids


def load_run(name: str) -> tuple[list[dict], dict] | None:
    d = REPO_ROOT / eval_config()["harness"]["runs_dir"]
    p, m = d / f"{name}.jsonl", d / f"{name}.meta.json"
    if not p.exists():
        return None
    return [json.loads(line) for line in p.read_text().splitlines() if line.strip()], json.loads(m.read_text())


def _pct(v: float) -> str:
    return "n/a" if v != v else f"{100 * v:.1f}"


def _ci(s: dict, key: str) -> str:
    lo, hi = s[f"{key}_ci"]
    return f"{_pct(s[key])} [{_pct(lo)}, {_pct(hi)}]"


def _summ(traces, cfg):
    h = cfg["harness"]
    return summarize(traces, int(h["bootstrap_resamples"]), float(h["ci_level"]), int(cfg["seed"]))


HDR = ["row", "setup", "n (pos/neg)", "found % [95% CI]", "FP % on neg [95% CI]", "accuracy %", "wrong loc. %",
       "calls / query", "fixations / query", "pixels sampled % (unique)", "vision tokens", "output tokens",
       "PNG KB", "time-to-answer p50 / p95 (ms)*"]


def _row(rid: str, label: str, s: dict | None, lat: dict | None) -> str:
    if s is None:
        return "| " + " | ".join([rid, label] + ["pending"] + [""] * (len(HDR) - 3)) + " |"
    la = f"{1000 * lat['tta_p50']:.0f} / {1000 * lat['tta_p95']:.0f}" if lat and lat.get("n") else "n/a"
    return "| " + " | ".join([
        rid, label, f"{s['n']} ({s['n_pos']}/{s['n_neg']})", _ci(s, "found"), _ci(s, "fp_rate"),
        _pct(s["accuracy"]), _pct(s["wrong_location"]), f"{s['calls']:.2f}", f"{s['fixations']:.2f}",
        f"{_pct(s['pixels_frac'])} ({_pct(s['pixels_unique_frac'])})", f"{s['vision_tokens']:.0f}",
        f"{s['completion_tokens']:.1f}", f"{s['png_bytes'] / 1000:.0f}", la]) + " |"


def summary_table(rows: list[tuple[str, str, list[dict] | None, list[dict] | None]], cfg) -> list[str]:
    out = ["| " + " | ".join(HDR) + " |", "|" + "---|" * len(HDR)]
    for rid, label, acc, lat in rows:
        s = _summ(acc, cfg) if acc else None
        if s is not None:
            s["fp_rate_ci"] = s["fp_ci"]
        out.append(_row(rid, label, s, latency(lat) if lat else None))
    return out


def main() -> None:
    cfg = eval_config()
    spec = run_specs()
    test_ids, all_ids = split_ids(cfg, "test"), split_ids(cfg, "all")
    L = ["# Results", "",
         f"Generated by `make table` from `results/runs/` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC. "
         "Do not edit by hand.", "",
         "- Frozen manifest: 500 queries (400 positive / 100 negative) on COCO val2017; **test** = 450 (all minus the "
         "50-query dev split used for every prompt/setting choice), **all** = 500.",
         "- **found %**: positives where the strategy confirmed the target AND its final point lies inside a ground-truth "
         "box. **FP %**: negatives where it reported found. **accuracy**: both combined. **wrong loc.**: positives "
         "reported found with the point outside every box. CIs: percentile bootstrap, "
         f"{cfg['harness']['bootstrap_resamples']} resamples, seed {cfg['seed']}.",
         "- **pixels sampled**: source pixels of every image sent / frame pixels (eye search's thumbnail counts on every "
         "fixation); in parentheses each distinct image counted once.",
         "- Accuracy, pixels and tokens come from accuracy runs (concurrency "
         f"{cfg['harness']['concurrency']}). *Latency comes **only** from separate runs on a seeded "
         f"{cfg['harness']['latency_subset_size']}-query subset of test at **concurrency "
         f"{cfg['harness']['latency_concurrency']}** after warmup (time-to-answer = sum of call times, server on the "
         "same VM).", ""]

    rows_cfg = spec["table"]
    loaded = {}
    for rid, r in rows_cfg.items():
        acc = load_run(r["acc"]) if "acc" in r else None
        lat = load_run(r["lat"]) if "lat" in r else None
        loaded[rid] = (r, acc, lat)

    refs = {rid: (r, load_run(r["acc"]) if "acc" in r else None, load_run(r["lat"]) if "lat" in r else None)
            for rid, r in (spec.get("reference") or {}).items()}
    for split_name, ids in [("test (450)", test_ids), ("all (500)", all_ids)]:
        L += [f"## Main table, split: {split_name}", ""]
        rows = []
        for rid, (r, acc, lat) in loaded.items():
            a = [t for t in acc[0] if t["meta"]["query_id"] in ids] if acc else None
            if a is not None and len(a) < len(ids):
                a = None  # run does not cover this split (e.g. a test-only run in the "all" table)
            rows.append((rid, r["label"] + (f" ({r['pending']})" if "pending" in r else "") +
                         ("" if a is not None or not acc else " (test split only)"), a, lat[0] if lat else None))
        L += summary_table(rows, cfg) + [""]
        if refs:
            L += [f"**Reference rows ({split_name}), NOT part of R1-R7:** the fine-tuned model with the single-call "
                  "strategies (is eye search still ahead once both use the fine-tuned model?), and the base model's "
                  "eye search with a 192 px thumbnail from the Step 5 sweep.", ""]
            rrows = []
            for rid, (r, acc, lat) in refs.items():
                a = [t for t in acc[0] if t["meta"]["query_id"] in ids] if acc else None
                if a is not None and len(a) < len(ids):
                    a = None
                rrows.append((f"ref {rid}", r["label"] + ("" if a is not None or not acc else " (test split only)"),
                              a, lat[0] if lat else None))
            L += summary_table(rrows, cfg) + [""]

    L += ["## Breakdowns (test split)", "", "### found % by target size (COCO buckets) and FP % on negatives", "",
          "| row | small | medium | large | negatives: FP % |", "|---|---|---|---|---|"]
    for rid, (r, acc, _) in {**loaded, **{f"ref {k}": v for k, v in refs.items()}}.items():
        if not acc:
            continue
        b = breakdown([t for t in acc[0] if t["meta"]["query_id"] in test_ids], by_size,
                      int(cfg["harness"]["bootstrap_resamples"]), float(cfg["harness"]["ci_level"]), int(cfg["seed"]))
        cell = lambda k: f"{_pct(b[k]['found'])} (n={b[k]['n_pos']})" if k in b else "-"  # noqa: E731
        L.append(f"| {rid} | {cell('small')} | {cell('medium')} | {cell('large')} | "
                 f"{_pct(b['negative']['fp_rate'])} (n={b['negative']['n_neg']}) |")
    L += ["", "### by query type", "", "| row | food: found % | food: FP % | single category: found % | single category: FP % |",
          "|---|---|---|---|---|"]
    for rid, (r, acc, _) in {**loaded, **{f"ref {k}": v for k, v in refs.items()}}.items():
        if not acc:
            continue
        b = breakdown([t for t in acc[0] if t["meta"]["query_id"] in test_ids], by_query_type)
        f, c = b["food"], b["single category"]
        L.append(f"| {rid} | {_pct(f['found'])} (n={f['n_pos']}) | {_pct(f['fp_rate'])} (n={f['n_neg']}) | "
                 f"{_pct(c['found'])} (n={c['n_pos']}) | {_pct(c['fp_rate'])} (n={c['n_neg']}) |")

    # paired comparisons (same test queries) and second-fixation analysis
    h = cfg["harness"]
    pairs = spec.get("paired") or []
    if pairs:
        L += ["", "## Paired comparisons (test split, same queries; b minus a, paired bootstrap 95% CI)", "",
              "| comparison | a | b | metric | n | a % | b % | diff (pp) [95% CI] | wrong->right | right->wrong |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for a_run, b_run, label in pairs:
            ra, rb = load_run(a_run), load_run(b_run)
            if not (ra and rb):
                L.append(f"| {label} | {a_run} | {b_run} | pending | | | | | | |")
                continue
            ta = [t for t in ra[0] if t["meta"]["query_id"] in test_ids]
            tb = [t for t in rb[0] if t["meta"]["query_id"] in test_ids]
            for metric in ["found", "accuracy"]:
                c = paired_compare(ta, tb, metric, int(h["bootstrap_resamples"]), float(h["ci_level"]), int(cfg["seed"]))
                lo, hi = c["diff_ci"]
                L.append(f"| {label} | {a_run} | {b_run} | {metric}{' (positives)' if metric == 'found' else ''} | {c['n']} | "
                         f"{_pct(c['a'])} | {_pct(c['b'])} | {100 * c['diff']:+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}] | "
                         f"{c['wrong_to_right']} | {c['right_to_wrong']} |")
    sf_runs = spec.get("second_fixation") or []
    if sf_runs:
        L += ["", "## Second fixation after a rejected crop (test split)", "",
              "| run | searches | with a rejected crop (on positives) | took a 2nd fixation (on positives) | "
              "found after the 2nd fixation | false positive after it | reached a 3rd fixation | repeats |",
              "|---|---|---|---|---|---|---|---|"]
        for run in sf_runs:
            r = load_run(run)
            if not r:
                L.append(f"| {run} | pending | | | | | | |")
                continue
            x = second_fixation([t for t in r[0] if t["meta"]["query_id"] in test_ids])
            L.append(f"| {run} | {x['searches']} | {x['with_rejected_crop']} ({x['rejected_on_positives']}) | "
                     f"{x['took_second_fixation']} ({x['second_fixation_on_positives']}) | {x['found_after_second_fixation']} | "
                     f"{x['false_positive_after_second_fixation']} | {x['third_fixation']} | {x['repeats']} |")

    # extra comparisons that are runs, not table rows
    extra = [("R4 refined point ON (default)", "R4_eye_search", test_ids),
             ("R4 refined point OFF", "R4_refine_off", test_ids)]
    if all(load_run(n) for _, n, _ in extra):
        L += ["", "## Eye search: refined point on vs off (test split, accuracy runs)", ""]
        L += summary_table([(lbl, "", [t for t in load_run(n)[0] if t["meta"]["query_id"] in ids], None)
                            for lbl, n, ids in extra], cfg)
    dev_runs = [n for n in spec["runs"] if n.startswith("dev_")]
    if any(load_run(n) for n in dev_runs):
        L += ["", "## Part A choices on the dev split (50 queries; accuracy runs, concurrency 8)", ""]
        L += summary_table([(n, json.dumps(spec["runs"][n].get("set", {})), load_run(n)[0], None)
                            for n in dev_runs if load_run(n)], cfg)
    out = REPO_ROOT / "results" / "table.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwrote {out.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
