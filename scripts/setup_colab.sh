#!/usr/bin/env bash
# Idempotent Colab setup: venvs, package install, env file, GPU info.
# Safe to re-run every session. Never mounts Drive (do that in the notebook).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

PYTHON_VERSION="3.12"
DRIVE_ROOT="/content/drive/MyDrive"
PROJECT_DRIVE_DIR="${PROJECT_DRIVE_DIR:-$DRIVE_ROOT/foveated-vlm-search}"
# Storage policy: regenerable things on the local disk (wiped each session), Drive only for small
# irreplaceable files (eval images, LoRA adapter). See NOTES.md "Storage policy".
LOCAL_DIR="${FVS_LOCAL_DIR:-/content/fvs_local}"
VENV_SERVE="$REPO/.venv-serve"
VENV_TRAIN="$REPO/.venv-train"
VENV_QUANT="$REPO/.venv-quant"
# Colab sets UV_SYSTEM_PYTHON=true globally; we always target explicit venvs.
unset UV_SYSTEM_PYTHON

SERVE_IMPORTS="import vllm, torch, transformers, openai, httpx, fastapi, uvicorn, PIL, pycocotools, pandas, matplotlib, foveated_search"
QUANT_IMPORTS="import llmcompressor, compressed_tensors, torch, transformers, foveated_search"
TRAIN_IMPORTS="import torch, transformers, peft, trl, datasets, accelerate, qwen_vl_utils, PIL, pycocotools, foveated_search; from transformers import Qwen3VLForConditionalGeneration"

declare -a TIMINGS=()
phase_start() { PHASE_NAME="$1"; PHASE_T0=$(date +%s); echo; echo "==> [$PHASE_NAME]"; }
phase_end()   { local dt=$(( $(date +%s) - PHASE_T0 )); TIMINGS+=("$(printf '%-34s %5ss' "$PHASE_NAME" "$dt")"); echo "    done in ${dt}s"; }
TOTAL_T0=$(date +%s)

# ---------------------------------------------------------------- Drive
phase_start "check Drive + create folders"
if [ ! -d "$DRIVE_ROOT" ]; then
  echo "ERROR: $DRIVE_ROOT not found. Google Drive is not mounted." >&2
  echo "       Run the notebook's setup cell (drive.mount('/content/drive')) and re-run 'make setup'." >&2
  exit 1
fi
mkdir -p "$PROJECT_DRIVE_DIR/data/coco_val_eval" "$PROJECT_DRIVE_DIR/adapters"
for d in data checkpoints hf_hub_cache models; do mkdir -p "$LOCAL_DIR/$d"; done
echo "    Drive project dir: $PROJECT_DRIVE_DIR ($(du -sh "$PROJECT_DRIVE_DIR" 2>/dev/null | cut -f1) used, budget ~500 MB)"
echo "    Local dir:         $LOCAL_DIR ($(df -h /content | awk 'NR==2{print $4}') free on /content)"
phase_end

# ---------------------------------------------------------------- uv
phase_start "install uv (if missing)"
if command -v uv >/dev/null 2>&1; then
  echo "    uv present: $(uv --version)"
else
  curl -LsSf https://astral.sh/uv/install.sh | sh
  export PATH="$HOME/.local/bin:$PATH"
  echo "    installed: $(uv --version)"
fi
phase_end

# ---------------------------------------------------------------- env file
phase_start "write scripts/env.sh"
cat > "$REPO/scripts/env.sh" <<EOF
# Generated by scripts/setup_colab.sh. No secrets. Source with: source scripts/env.sh
# NOTE: HF_HOME is deliberately NOT set (it would move the HF token location and break login).
# Local disk (wiped each session): everything re-downloadable / regenerable.
export FVS_LOCAL_DIR="$LOCAL_DIR"
export FVS_DATA_DIR="$LOCAL_DIR/data"
export FVS_CHECKPOINTS_DIR="$LOCAL_DIR/checkpoints"
export FVS_MODELS_DIR="$LOCAL_DIR/models"
export HF_HUB_CACHE="$LOCAL_DIR/hf_hub_cache"
# Drive: small irreplaceable files only (project budget ~500 MB).
export PROJECT_DRIVE_DIR="$PROJECT_DRIVE_DIR"
export FVS_DRIVE_EVAL_IMAGES_DIR="$PROJECT_DRIVE_DIR/data/coco_val_eval"
export FVS_DRIVE_ADAPTERS_DIR="$PROJECT_DRIVE_DIR/adapters"
# huggingface_hub>=1.3x "shared blob" store left a 79-byte pointer file instead of a working
# symlink for model.safetensors on Drive (NOTES.md Gotchas). Classic per-repo blobs work.
export HF_HUB_DISABLE_SHARED_BLOBS=1
export FVS_REPO="$REPO"
export VENV_SERVE="$VENV_SERVE"
export VENV_TRAIN="$VENV_TRAIN"
export VENV_QUANT="$VENV_QUANT"
EOF
echo "    wrote scripts/env.sh"
phase_end

# ---------------------------------------------------------------- helpers
venv_ok() {  # $1=venv dir, $2=import statement
  [ -x "$1/bin/python" ] && "$1/bin/python" -c "$2" >/dev/null 2>&1
}
torch_version() { "$1/bin/python" -c "import torch; print(torch.__version__)"; }
freeze_lock() {  # $1=venv, $2=lock path
  { echo "# Frozen by scripts/setup_colab.sh on $(date -u +%Y-%m-%dT%H:%MZ), python $PYTHON_VERSION"
    uv pip freeze --python "$1/bin/python" | grep -v -E '^(-e |foveated-search)'
  } > "$2"
  echo "    froze $(grep -vc '^#' "$2") packages -> ${2#$REPO/}"
}

setup_venv() {  # $1=name (serve|train|quant), $2=venv dir, $3=import statement
  local name="$1" venv="$2" imports="$3" py="$2/bin/python"
  if venv_ok "$venv" "$imports"; then
    echo "    exists and key imports work -> skip"; return
  fi
  [ -x "$py" ] || uv venv --python "$PYTHON_VERSION" "$venv"
  if [ -f "requirements/$name.lock" ]; then
    echo "    installing from requirements/$name.lock"
    uv pip install --python "$py" -r "requirements/$name.lock"
  else
    if [ "$name" = serve ]; then
      # vLLM first, so we can detect anything else in serve.in trying to move its torch.
      echo "    no lock: installing vllm first, then the rest of serve.in"
      uv pip install --python "$py" "$(grep -E '^vllm' requirements/serve.in)"
      local tb; tb=$(torch_version "$venv"); echo "    torch installed by vllm: $tb"
      uv pip install --python "$py" -r requirements/serve.in
      local ta; ta=$(torch_version "$venv")
      if [ "$tb" != "$ta" ]; then
        echo "ERROR: torch changed $tb -> $ta after installing serve.in. Do not force; see NOTES.md." >&2
        exit 1
      fi
      "$py" -c "import vllm; print('    torch unchanged; vllm still imports:', vllm.__version__)"
    else
      echo "    no lock: installing from requirements/$name.in"
      uv pip install --python "$py" -r "requirements/$name.in"
    fi
    freeze_lock "$venv" "requirements/$name.lock"
  fi
  uv pip install --python "$py" -e .
}

phase_start ".venv-serve"; setup_venv serve "$VENV_SERVE" "$SERVE_IMPORTS"; phase_end
phase_start ".venv-train"; setup_venv train "$VENV_TRAIN" "$TRAIN_IMPORTS"; phase_end
phase_start ".venv-quant"; setup_venv quant "$VENV_QUANT" "$QUANT_IMPORTS"; phase_end

# ---------------------------------------------------------------- verify imports
phase_start "verify key imports"
"$VENV_SERVE/bin/python" -c "$SERVE_IMPORTS; print('    serve: vllm', vllm.__version__, '| torch', torch.__version__, '| transformers', transformers.__version__)"
"$VENV_TRAIN/bin/python" -c "$TRAIN_IMPORTS; print('    train: torch', torch.__version__, '| transformers', transformers.__version__, '| peft', peft.__version__, '| trl', trl.__version__)"
"$VENV_QUANT/bin/python" -c "$QUANT_IMPORTS; print('    quant: llmcompressor', llmcompressor.__version__, '| compressed-tensors', compressed_tensors.__version__, '| torch', torch.__version__, '| transformers', transformers.__version__)"
phase_end

# ---------------------------------------------------------------- GPU
phase_start "GPU info"
nvidia-smi --query-gpu=name,memory.total,compute_cap,driver_version --format=csv
phase_end

echo
echo "==> Phase timings"
printf '    %s\n' "${TIMINGS[@]}"
echo "    TOTAL                              $(( $(date +%s) - TOTAL_T0 ))s"
echo "==> setup complete. Next: make check"
